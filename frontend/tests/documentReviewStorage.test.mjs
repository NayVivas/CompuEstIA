// Ejecutar con fake-indexeddb instalado como dependencia de desarrollo.
import assert from 'node:assert/strict';
import { indexedDB } from 'fake-indexeddb';
import { saveDecision, getDecisions, applyDecisions, fileHash, storePdf, getPdf } from '../src/services/documentReviewStorage.js';
globalThis.indexedDB = indexedDB;
const file = new Blob(['PDF de prueba']);
const sha256 = await fileHash(file);
const decision = { sha256, pagina: 1, revisor: 'Ingeniera A', motivo: 'Verificación documental de prueba', objetivos: { disciplinas: ['estructura'], roles_documentales: ['detalle'], contenidos: ['columnas_pilares'] } };
const saved = await saveDecision('proyecto-1', decision);
assert.equal(saved.version, 1);
assert.equal((await getDecisions('proyecto-1'))[0].historial.length, 1);
assert.equal((await getDecisions('proyecto-2')).length, 0);
await assert.rejects(saveDecision('proyecto-1', decision, 0));
const changed = await saveDecision('proyecto-1', { ...decision, motivo: 'Segunda decisión justificada' }, 1);
assert.equal(changed.historial.length, 2);
const doc = { sha256, paginas: [{ pagina: 1, caracteres: 20, requiere_revision: true, clasificacion: { objetivos: { disciplinas: { etiquetas: ['arquitectura'] } } } }] };
const review = { documentos: [doc], resumen: {} };
const restored = applyDecisions(review, await getDecisions('proyecto-1'));
assert.equal(restored.documentos[0].paginas[0].estado, 'revisado_profesional');
assert.equal(restored.documentos[0].paginas[0].clasificacion_automatica.objetivos.disciplinas.etiquetas[0], 'arquitectura');
assert.equal(restored.resumen.paginas_para_revision, 0);
assert.equal(review.documentos[0].paginas[0].requiere_revision, true);
const other = applyDecisions({ documentos: [{ ...doc, sha256: 'otro' }] }, [changed]);
assert.equal(other.documentos[0].paginas[0].decision_documental, undefined);
await storePdf(sha256, file);
assert.equal(await (await getPdf(sha256)).text(), await file.text());
await assert.rejects(storePdf(sha256, new Blob(['distinto'])));
// No confirmar un guardado si la transacción aborta por cuota.
const originalOpen = indexedDB.open.bind(indexedDB);
const { IDBObjectStore } = await import('fake-indexeddb');
const originalPut = IDBObjectStore.prototype.put;
IDBObjectStore.prototype.put = function () { this.transaction.abort(); throw new DOMException('Cuota excedida', 'QuotaExceededError'); };
await assert.rejects(saveDecision('proyecto-1', decision, 2));
IDBObjectStore.prototype.put = originalPut;
assert.equal((await getDecisions('proyecto-1'))[0].version, 2);
assert.ok(originalOpen);
console.log('Persistencia, historial, aislamiento por proyecto/PDF, conflicto entre pestañas y fallo de cuota: correctos.');
const { getTechnicalNotes, saveTechnicalNote } = await import('../src/services/documentReviewStorage.js');
const note = await saveTechnicalNote('proyecto-1', 'issue-1', { revisor: 'Ingeniera A', motivo: 'Comparar los detalles originales' });
assert.equal(note.historial.length, 1);
assert.equal((await getDecisions('proyecto-1')).length, 1);
assert.equal((await getTechnicalNotes('proyecto-1')).length, 1);
assert.equal((await getTechnicalNotes('proyecto-2')).length, 0);
await assert.rejects(saveTechnicalNote('proyecto-1', 'issue-1', { revisor: 'B', motivo: 'Otro' }, 0));
assert.equal((await getTechnicalNotes('proyecto-1'))[0].historial[0].motivo, 'Comparar los detalles originales');
console.log('Observaciones técnicas separadas de las decisiones documentales: correcto.');
const { getRowCorrections, storeRowCorrections } = await import('../src/services/documentReviewStorage.js');
const correction = { sha256, pagina: 1, fila: 13, referencia_original: 'F12', referencia_correcta: 'F13', revisor: 'Profesional', motivo: 'Verificación de referencia de planta' };
await storeRowCorrections('proyecto-1', [correction], [sha256], []);
assert.equal((await getRowCorrections('proyecto-1'))[0].referencia_correcta, 'F13');
// Repetir exactamente el mismo envío es idempotente, aunque conserve la
// instantánea anterior al primer guardado (por ejemplo, por un doble clic).
await storeRowCorrections('proyecto-1', [correction], [sha256], []);
assert.equal((await getDecisions('proyecto-1')).length, 1);
assert.equal((await getTechnicalNotes('proyecto-1')).length, 1);
assert.equal((await getRowCorrections('proyecto-2')).length, 0);
await assert.rejects(storeRowCorrections('proyecto-1', [], [sha256], []));
const previousCorrections = await getRowCorrections('proyecto-1');
await storeRowCorrections('proyecto-1', [], [sha256], previousCorrections);
assert.equal((await getRowCorrections('proyecto-1')).length, 0);
console.log('Correcciones de filas persistentes y separadas de notas/clasificaciones: correcto.');
const { getTechnicalResolutions, storeTechnicalResolutions } = await import('../src/services/documentReviewStorage.js');
const mapping = { accion: 'reasignar_referencia_detalle', sha256, pagina: 2, referencia_original: 'C4', referencia_correcta: 'C3', revisor: 'Ingeniera A', motivo: 'Rótulo contrastado contra la planta estructural.' };
await storeTechnicalResolutions('proyecto-1', [mapping], [sha256], []);
let resolutions = await getTechnicalResolutions('proyecto-1');
assert.equal(resolutions[0].referencia_correcta, 'C3');
await storeTechnicalResolutions('proyecto-1', [mapping], [sha256], []);
assert.equal((await getTechnicalResolutions('proyecto-2')).length, 0);
const manual = { accion: 'definir_seccion_columna', sha256, pagina: 16, referencia: 'C19', dimension_1_m: .25, dimension_2_m: .25, revisor: 'Ingeniera A', motivo: 'Cotas verificadas sobre el detalle estructural.' };
const reorderedSnapshot = resolutions.map(record => Object.fromEntries(Object.entries(record).reverse()));
await storeTechnicalResolutions('proyecto-1', [mapping, manual], [sha256], reorderedSnapshot);
resolutions = await getTechnicalResolutions('proyecto-1');
assert.equal(resolutions.length, 2);
assert.equal(resolutions.find(item => item.accion === 'definir_seccion_columna').dimension_1_m, .25);
await assert.rejects(storeTechnicalResolutions('proyecto-1', [], [sha256], []));
console.log('Resoluciones técnicas persistentes, auditables y aisladas por proyecto: correcto.');
